"""The typed-decision record: one schema for every distillation source.

A record is ``{id, state, questions{qid: {type, instructions?, criteria}}, gold
per question, split, source, licence}`` plus a per-record ``gold_provenance``
saying who produced the gold (``human`` or ``model-generated``). Records are
frozen and keyed by the source's own ``id``, never by row position.

Question types: ``choice`` (>= 2 options), ``noul`` (a true/false question;
gold is the probability that it is true) and ``score`` (>= 2 ordered levels,
named by index ``"0"``, ``"1"`` ...). ``criteria`` is an ordered tuple of
``(name, description)`` pairs. Gold is soft where the source is soft: a
:class:`Gold` keeps the label, the full probabilities and the confidence.

Loaders: :func:`from_typed_decisions_row` (LocalLLaMA/typed-decisions, gold is
model-generated by a ~4B teacher's 3-sample mean), :func:`from_jev_bench_row`
(Praveenrajus/jev-bench, labels are human, from the source datasets) and
:func:`from_domain` (a tool :class:`~jev_factory.domain.model.Domain` as one
choice question). Parquet is read by :func:`load_parquet`, which imports
pyarrow lazily. Stdlib only at import time.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from typing import Any

QUESTION_TYPES: frozenset[str] = frozenset({"choice", "noul", "score"})
GOLD_PROVENANCES: frozenset[str] = frozenset({"human", "model-generated"})
NOUL_OPTIONS = ("false", "true")

#: The one question a tool domain renders as.
DOMAIN_QID = "action"

TYPED_DECISIONS_SOURCE = "LocalLLaMA/typed-decisions"
JEV_BENCH_SOURCE = "Praveenrajus/jev-bench"
TYPED_DECISIONS_LICENCE = "Apache-2.0"


class RecordError(ValueError):
    """Base of every named record-validation error; ``code`` is the stable name."""

    code = "record_error"

    def __init__(self, message: str) -> None:
        super().__init__(f"{self.code}: {message}")


class UnknownQuestionType(RecordError):
    code = "unknown_question_type"


class TooFewOptions(RecordError):
    code = "too_few_options"


class TooFewLevels(RecordError):
    code = "too_few_levels"


class GoldOutsideOptions(RecordError):
    code = "gold_outside_options"


class MissingField(RecordError):
    code = "missing_field"


class UnknownGoldProvenance(RecordError):
    code = "unknown_gold_provenance"


class BadProbability(RecordError):
    code = "bad_probability"


class DuplicateCriterion(RecordError):
    code = "duplicate_criterion"


class MissingAttribution(RecordError):
    code = "missing_attribution"


class InvalidSystemOneBody(RecordError):
    code = "invalid_systemone_body"


#: Licences that oblige the redistributor to credit the source.
ATTRIBUTION_LICENCES: frozenset[str] = frozenset({"cc-by-4.0"})


Criteria = tuple[tuple[str, str], ...]


def _criteria(value: Any) -> Criteria:
    """Normalise list-of-names, list-of-{name,description} or {name: description}."""
    if value is None:
        return ()
    if isinstance(value, Mapping):
        return tuple((str(k), "" if v is None else str(v)) for k, v in value.items())
    out: list[tuple[str, str]] = []
    for item in value:
        if isinstance(item, Mapping):
            name = item.get("name", item.get("id", item.get("label")))
            if name is None:
                raise MissingField(f"criterion without a name: {dict(item)!r}")
            out.append((str(name), str(item.get("description", item.get("desc", "")) or "")))
        elif isinstance(item, (list, tuple)) and len(item) == 2:
            out.append((str(item[0]), str(item[1])))
        else:
            out.append((str(item), ""))
    return tuple(out)


@dataclass(frozen=True)
class Question:
    """One question: its type, optional instructions and ordered criteria."""

    type: str
    criteria: Criteria
    instructions: str | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "criteria", _criteria(self.criteria))

    @property
    def names(self) -> tuple[str, ...]:
        return tuple(name for name, _ in self.criteria)

    def validate(self, qid: str = "?", rid: str = "?") -> None:
        where = f"record {rid!r} question {qid!r}"
        if self.type not in QUESTION_TYPES:
            raise UnknownQuestionType(f"{where}: {self.type!r} not in {sorted(QUESTION_TYPES)}")
        names = self.names
        if len(set(names)) != len(names):
            raise DuplicateCriterion(f"{where}: duplicate criteria in {list(names)}")
        if self.type == "score" and len(names) < 2:
            raise TooFewLevels(f"{where}: score needs >= 2 levels, got {len(names)}")
        if self.type == "choice" and len(names) < 2:
            raise TooFewOptions(f"{where}: choice needs >= 2 options, got {len(names)}")
        if self.type == "noul" and names != NOUL_OPTIONS:
            raise TooFewOptions(f"{where}: noul needs options {list(NOUL_OPTIONS)}")

    def to_json(self) -> dict[str, Any]:
        out: dict[str, Any] = {"type": self.type, "criteria": [list(c) for c in self.criteria]}
        if self.instructions is not None:
            out["instructions"] = self.instructions
        return out

    @classmethod
    def from_json(cls, data: Mapping[str, Any]) -> Question:
        if "type" not in data:
            raise MissingField("question without a type")
        qtype = str(data["type"])
        raw = data.get("criteria")
        if (
            qtype == "score"
            and isinstance(raw, (list, tuple))
            and all(isinstance(i, str) for i in raw)
        ):
            criteria: Any = [(str(i), d) for i, d in enumerate(raw)]
        else:
            criteria = raw
        return cls(type=qtype, criteria=_criteria(criteria), instructions=data.get("instructions"))


@dataclass(frozen=True)
class Gold:
    """Gold for one question.

    ``label`` is the hard answer (an option or level name; for ``noul`` the
    "true"/"false" label, optional). ``probabilities`` is the full soft
    distribution over the question's names, when the source has one.
    ``probability_true`` is the noul gold (hard 0.0/1.0 from a hard label).
    ``score`` is the typed-decisions expected score for ``score`` questions.
    """

    label: str | None = None
    probabilities: Mapping[str, float] | None = None
    confidence: float | None = None
    probability_true: float | None = None
    score: float | None = None

    def __post_init__(self) -> None:
        if self.probabilities is not None:
            object.__setattr__(self, "probabilities", dict(self.probabilities))

    def check(self, qid: str, question: Question, rid: str = "?") -> None:
        where = f"record {rid!r} question {qid!r}"
        names = question.names
        if question.type == "noul":
            p = self.probability_true
            if p is None:
                raise MissingField(f"{where}: noul gold needs probability_true")
            if not 0.0 <= p <= 1.0:
                raise BadProbability(f"{where}: probability_true {p} outside [0, 1]")
        elif self.label is None:
            raise MissingField(f"{where}: gold has no label")
        elif self.label not in names:
            raise GoldOutsideOptions(f"{where}: gold {self.label!r} not in {list(names)}")
        if self.label is not None and question.type == "noul" and self.label not in names:
            raise GoldOutsideOptions(f"{where}: gold {self.label!r} not in {list(names)}")
        if self.probabilities is not None:
            stray = sorted(set(self.probabilities) - set(names))
            if stray:
                raise GoldOutsideOptions(f"{where}: probabilities for {stray} not in {list(names)}")
            if any(not 0.0 <= v <= 1.0 for v in self.probabilities.values()):
                raise BadProbability(f"{where}: probability outside [0, 1]")

    def to_json(self) -> dict[str, Any]:
        out = {
            "label": self.label,
            "probabilities": None if self.probabilities is None else dict(self.probabilities),
            "confidence": self.confidence,
            "probability_true": self.probability_true,
            "score": self.score,
        }
        return {k: v for k, v in out.items() if v is not None}

    @classmethod
    def from_json(cls, data: Mapping[str, Any]) -> Gold:
        return cls(
            label=None if data.get("label") is None else str(data["label"]),
            probabilities=data.get("probabilities"),
            confidence=data.get("confidence"),
            probability_true=data.get("probability_true"),
            score=data.get("score"),
        )


@dataclass(frozen=True)
class Record:
    """One typed decision; validated on construction."""

    id: str
    state: str
    questions: Mapping[str, Question]
    gold: Mapping[str, Gold]
    split: str
    source: str
    licence: str
    gold_provenance: str
    #: Upstream dataset id (jev-bench ``meta.hf_id``); feeds the contamination check.
    hf_id: str | None = None
    #: Fold-grouping key (typed-decisions ``workflow``); falls back to identical state.
    group: str | None = None
    #: Credit line for the source; required when the licence is cc-by-4.0.
    attribution: str | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "questions", dict(self.questions))
        object.__setattr__(self, "gold", dict(self.gold))
        self.validate()

    def validate(self) -> None:
        for name in ("id", "state", "split", "source", "licence"):
            if not getattr(self, name):
                raise MissingField(f"record field {name!r} is empty")
        if not self.questions:
            raise MissingField(f"record {self.id!r} has no questions")
        if self.gold_provenance not in GOLD_PROVENANCES:
            raise UnknownGoldProvenance(
                f"record {self.id!r}: {self.gold_provenance!r} not in {sorted(GOLD_PROVENANCES)}"
            )
        if self.licence.strip().lower() in ATTRIBUTION_LICENCES and not (
            isinstance(self.attribution, str) and self.attribution.strip()
        ):
            raise MissingAttribution(
                f"record {self.id!r}: licence {self.licence!r} needs an attribution string"
            )
        self._check_systemone_body()
        for qid, question in self.questions.items():
            question.validate(qid, self.id)
            if qid not in self.gold:
                raise MissingField(f"record {self.id!r}: no gold for question {qid!r}")
            self.gold[qid].check(qid, question, self.id)
        extra = sorted(set(self.gold) - set(self.questions))
        if extra:
            raise GoldOutsideOptions(f"record {self.id!r}: gold for unknown questions {extra}")

    def _check_systemone_body(self) -> None:
        """The record must render as a well-formed /v1/systemone body (``{state, questions}``)."""
        where = f"record {self.id!r}"
        if not isinstance(self.state, str):
            raise InvalidSystemOneBody(f"{where}: state must be a string")
        for qid, question in self.questions.items():
            if not isinstance(qid, str) or not qid.strip():
                raise InvalidSystemOneBody(
                    f"{where}: question id {qid!r} is not a non-empty string"
                )
            if question.instructions is not None and not isinstance(question.instructions, str):
                raise InvalidSystemOneBody(f"{where} question {qid!r}: instructions not a string")
            if question.type == "noul":
                continue
            if any(not name.strip() for name in question.names):
                raise InvalidSystemOneBody(f"{where} question {qid!r}: blank option name")

    def to_json(self) -> dict[str, Any]:
        out: dict[str, Any] = {
            "id": self.id,
            "state": self.state,
            "questions": {qid: q.to_json() for qid, q in self.questions.items()},
            "gold": {qid: g.to_json() for qid, g in self.gold.items()},
            "split": self.split,
            "source": self.source,
            "licence": self.licence,
            "gold_provenance": self.gold_provenance,
        }
        for name in ("hf_id", "group", "attribution"):
            if getattr(self, name) is not None:
                out[name] = getattr(self, name)
        return out

    @classmethod
    def from_json(cls, data: Mapping[str, Any]) -> Record:
        for key in ("id", "state", "questions", "gold", "split", "source", "licence"):
            if key not in data:
                raise MissingField(f"record json lacks {key!r}")
        return cls(
            id=str(data["id"]),
            state=str(data["state"]),
            questions={qid: Question.from_json(q) for qid, q in data["questions"].items()},
            gold={qid: Gold.from_json(g) for qid, g in data["gold"].items()},
            split=str(data["split"]),
            source=str(data["source"]),
            licence=str(data["licence"]),
            gold_provenance=str(data.get("gold_provenance", "")),
            hf_id=None if data.get("hf_id") is None else str(data["hf_id"]),
            group=None if data.get("group") is None else str(data["group"]),
            attribution=None if data.get("attribution") is None else str(data["attribution"]),
        )


