def _loads(value: Any) -> Any:
    return json.loads(value) if isinstance(value, (str, bytes)) else value


def _typed_decisions_gold(raw: Mapping[str, Any]) -> Gold:
    probs = raw.get("probabilities")
    p_true = raw.get("noul")
    if p_true is None and raw.get("type") == "noul" and probs:
        p_true = probs.get("true")
    return Gold(
        label=None if raw.get("label") is None else str(raw["label"]),
        probabilities=probs,
        confidence=raw.get("confidence"),
        probability_true=p_true,
        score=raw.get("score"),
    )


def from_typed_decisions_row(row: Mapping[str, Any]) -> Record:
    """A LocalLLaMA/typed-decisions row (JSON-string ``state``/``questions``/``gold``).

    Gold is soft and model-generated (a ~4B teacher's 3-sample mean); the full
    probabilities are kept. Licence is the dataset card's Apache-2.0.
    """
    for key in ("id", "split", "state", "questions", "gold"):
        if key not in row:
            raise MissingField(f"typed-decisions row lacks {key!r}")
    return Record(
        id=str(row["id"]),
        state=json.dumps(_loads(row["state"]), sort_keys=True, ensure_ascii=False),
        questions={str(q): Question.from_json(v) for q, v in _loads(row["questions"]).items()},
        gold={str(q): _typed_decisions_gold(g) for q, g in _loads(row["gold"]).items()},
        split=str(row["split"]),
        source=TYPED_DECISIONS_SOURCE,
        licence=TYPED_DECISIONS_LICENCE,
        gold_provenance="model-generated",
        group=None if row.get("workflow") in (None, "") else str(row["workflow"]),
    )


def from_jev_bench_row(row: Mapping[str, Any]) -> Record:
    """A Praveenrajus/jev-bench row; labels are human, from the source datasets.

    ``question`` is ``{type, instructions, criteria}`` (JSON text or object);
    options come from its criteria (a null description becomes ``""``). The
    label is an option key (choice), a level index (score) or ``"0"``/``"1"``
    (noul, stored as probability_true 0.0/1.0). ``soft_label``, when present,
    is the human vote shares and is kept as ``probabilities``. The licence is
    ``meta.license`` passed through verbatim.
    """
    for key in ("id", "source", "split", "state", "question", "label", "meta"):
        if key not in row:
            raise MissingField(f"jev-bench row lacks {key!r}")
    question = Question.from_json(_loads(row["question"]))
    meta = _loads(row["meta"])
    if not meta.get("license"):
        raise MissingField(f"jev-bench row {row['id']!r}: meta has no license")
    label = str(row["label"])
    soft = _loads(row["soft_label"]) if row.get("soft_label") else None
    if question.type == "noul":
        p_true = {"1": 1.0, "0": 0.0}.get(label)
        gold = Gold(
            label=NOUL_OPTIONS[int(p_true)] if p_true is not None else label,
            probability_true=p_true,
            probabilities=soft or None,
        )
    else:
        gold = Gold(label=label, probabilities=soft)
    return Record(
        id=str(row["id"]),
        state=json.dumps(_loads(row["state"]), sort_keys=True, ensure_ascii=False),
        questions={"q": question},
        gold={"q": gold},
        split=str(row["split"]),
        source=f"{JEV_BENCH_SOURCE}:{row['source']}",
        licence=str(meta["license"]),
        gold_provenance="human",
        hf_id=None if not meta.get("hf_id") else str(meta["hf_id"]),
    )


def content_id(*parts: Any) -> str:
    """A stable id derived from content, for sources that carry none."""
    blob = json.dumps(parts, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]


def from_domain(
    domain: Any,
    *,
    request: str,
    gold: str,
    gold_provenance: str,
    licence: str,
    split: str = "train",
    record_id: str | None = None,
) -> Record:
    """A tool :class:`Domain` as one ``choice`` question whose criteria are its operations."""
    criteria = tuple((op.name, op.description) for op in domain.operations)
    return Record(
        id=record_id or content_id(request, [c[0] for c in criteria]),
        state=request,
        questions={DOMAIN_QID: Question(type="choice", criteria=criteria)},
        gold={DOMAIN_QID: Gold(label=gold)},
        split=split,
        source=f"domain:{domain.name}",
        licence=licence,
        gold_provenance=gold_provenance,
    )


def load_parquet(
    path: str, loader: Any = from_typed_decisions_row, **kwargs: Any
) -> Iterable[Record]:
    """Yield records from a parquet file; pyarrow is imported here, lazily."""
    import pyarrow.parquet as pq  # noqa: PLC0415

    for row in pq.read_table(path).to_pylist():
        yield loader(row)
