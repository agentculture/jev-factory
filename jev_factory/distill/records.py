def _loads(value: Any) -> Any:
    return json.loads(value) if isinstance(value, (str, bytes)) else value


def content_id(*parts: Any) -> str:
    """A stable id derived from content, for sources that carry none."""
    blob = json.dumps(parts, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]


def from_typed_decisions_row(
    row: Mapping[str, Any], *, split: str = "train", licence: str = DEFAULT_LICENCE
) -> Record:
    """A LocalLLaMA/typed-decisions row (``state``/``questions``/``gold`` JSON columns).

    Gold is model-generated (a ~4B teacher's 3-sample mean). The row has no id
    column assumed: ``id`` is used if present, else a hash of state+questions.
    """
    for key in ("state", "questions", "gold"):
        if key not in row:
            raise MissingField(f"typed-decisions row lacks {key!r}")
    questions_raw = _loads(row["questions"])
    gold_raw = _loads(row["gold"])
    questions = {str(q): Question.from_json(v) for q, v in questions_raw.items()}
    rid = row.get("id") or content_id(row["state"], questions_raw)
    return Record(
        id=str(rid),
        state=str(row["state"]),
        questions=questions,
        gold={str(q): str(g) for q, g in gold_raw.items()},
        split=str(row.get("split") or split),
        source=TYPED_DECISIONS_SOURCE,
        licence=str(row.get("licence") or licence),
        gold_provenance="model-generated",
    )


def from_jev_bench_row(row: Mapping[str, Any], *, licence: str = DEFAULT_LICENCE) -> Record:
    """A Praveenrajus/jev-bench row; labels come from the human source datasets.

    ``question`` is a plain string or a JSON object with ``text``/``type``/
    ``criteria``. The offered options are the ``soft_label`` keys when it is a
    mapping (JSON text accepted), else the question's own criteria; ``label``
    is the gold. ``primitive`` is the question type when it names one, else
    ``choice``. ``source`` keeps the row's source dataset: ``jev-bench/<source>``.
    """
    for key in ("id", "source", "split", "state", "question", "label"):
        if key not in row:
            raise MissingField(f"jev-bench row lacks {key!r}")
    question = row["question"]
    if isinstance(question, str) and question.lstrip().startswith("{"):
        question = json.loads(question)
    qdict = dict(question) if isinstance(question, Mapping) else {"text": str(question)}
    soft = _loads(row.get("soft_label")) if row.get("soft_label") not in (None, "") else None
    criteria = _criteria(qdict.get("criteria", qdict.get("options")))
    if isinstance(soft, Mapping) and soft:
        criteria = criteria or _criteria(list(soft))
    primitive = str(row.get("primitive") or "")
    qtype = str(qdict.get("type") or (primitive if primitive in QUESTION_TYPES else "choice"))
    instructions = qdict.get("text") or qdict.get("instructions")
    return Record(
        id=str(row["id"]),
        state=str(row["state"]),
        questions={"q": Question(type=qtype, criteria=criteria, instructions=instructions)},
        gold={"q": str(row["label"])},
        split=str(row["split"]),
        source=f"{JEV_BENCH_SOURCE}:{row['source']}",
        licence=str(row.get("licence") or licence),
        gold_provenance="human",
    )


def from_domain(
    domain: Any,
    *,
    request: str,
    gold: str,
    gold_provenance: str,
    split: str = "train",
    licence: str = DEFAULT_LICENCE,
    record_id: str | None = None,
) -> Record:
    """A tool :class:`Domain` as one ``choice`` question whose criteria are its operations."""
    criteria = tuple((op.name, op.description) for op in domain.operations)
    return Record(
        id=record_id or content_id(request, [c[0] for c in criteria]),
        state=request,
        questions={DOMAIN_QID: Question(type="choice", criteria=criteria)},
        gold={DOMAIN_QID: gold},
        split=split,
        source=f"domain:{domain.name}",
        licence=licence,
        gold_provenance=gold_provenance,
    )


def load_parquet(
    path: str, loader: Any = from_typed_decisions_row, **kwargs: Any
) -> Iterable[Record]:
    """Yield records from a parquet file; pyarrow is imported here, lazily."""
    import pyarrow.parquet as pq  # noqa: PLC0415

    for row in pq.read_table(path).to_pylist():
        yield loader(row, **kwargs)
